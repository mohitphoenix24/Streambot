  function closePalette() { pal.classList.remove("open"); }

  function hl(text, terms) {
    let s = esc(text);
    terms.forEach((t) => { if (t.length > 1) s = s.replace(new RegExp(`(${t.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")})`, "ig"), "<mark>$1</mark>"); });
    return s;
  }

  function drawResults(q) {
    const terms = q.toLowerCase().split(/\s+/).filter(Boolean);
    let lessonHits, termHits;
    if (!terms.length) {
      lessonHits = learnLessons.slice(0, 8).map((l) => ({ l }));
      termHits = [];
    } else {
      lessonHits = lessons.map((l) => {
        let score = 0;
        const title = l.title.toLowerCase(), heads = l.headings.join(" ").toLowerCase(), sum = (l.summary || "").toLowerCase() + " " + l.module.title.toLowerCase() + " " + (l.tags || "").toLowerCase();
        for (const t of terms) {
          let s = 0;
          if (title.includes(t)) s += title.startsWith(t) ? 14 : 10;
          if (heads.includes(t)) s += 5;
          if (sum.includes(t)) s += 3;
          if (l.plain.includes(t)) s += 1;
          if (!s) return null;
          score += s;
        }
        return { l, score };
      }).filter(Boolean).sort((a, b) => b.score - a.score).slice(0, 10);
      termHits = glossary.filter((g) => terms.every((t) => g.term.toLowerCase().includes(t))).slice(0, 6);
    }
    const probHits = terms.length ? problems.filter((p) => terms.every((t) => (p.title + " " + p.tags.join(" ")).toLowerCase().includes(t))).slice(0, 8) : [];
    palItems = [];
    let html = "";
    const extHits = terms.length && EXT.search ? EXT.search(terms) : [];
    if (extHits.length) {
      html += `<div class="grp">${esc(EXT.searchLabel || "More")}</div>`;
      extHits.forEach((h) => {
        palItems.push(h.href);
        html += `<a class="res" href="${esc(h.href)}"><span class="r-icon">${icon(h.icon || "sheet")}</span><span class="r-main"><div class="r-title">${hl(h.title, terms)}</div><div class="r-sub">${esc(h.sub || "")}</div></span>${h.lvl ? lvlChip(h.lvl) : ""}</a>`;
      });
    }
    if (probHits.length) {
      html += `<div class="grp">Problems</div>`;
      probHits.forEach((p) => {
        palItems.push(`#/l/${p.lesson.id}~p-${p.id}`);
        html += `<a class="res" href="#/l/${esc(p.lesson.id)}~p-${esc(p.id)}"><span class="r-icon">${icon("target")}</span><span class="r-main"><div class="r-title">${hl(p.title, terms)}</div><div class="r-sub">${esc(p.lesson.title)}${p.tags.length ? " · " + esc(p.tags.join(", ")) : ""}</div></span>${lvlChip(p.level)}</a>`;
      });
    }
    if (lessonHits.length) {
      html += `<div class="grp">${terms.length ? "Lessons & projects" : "Start here"}</div>`;
      lessonHits.forEach(({ l }) => {
        const head = terms.length ? l.headings.find((h) => terms.some((t) => h.toLowerCase().includes(t))) : null;
        palItems.push(`#/l/${l.id}`);
        html += `<a class="res" href="#/l/${esc(l.id)}"><span class="r-icon">${icon(l.module.kind === "projects" ? l.icon || "flask" : l.module.icon)}</span><span class="r-main"><div class="r-title">${hl(l.title, terms)}</div><div class="r-sub">${esc(l.module.title)}${head ? " › " + hl(head, terms) : " · " + esc(l.summary || "")}</div></span>${lvlChip(l.level)}</a>`;
      });
    }
    if (termHits.length) {
      html += `<div class="grp">Definitions</div>`;
      termHits.forEach((g) => {
        palItems.push(`#/l/${g.lesson.id}~def-${slugify(g.term)}`);
        html += `<a class="res" href="#/l/${esc(g.lesson.id)}~def-${slugify(g.term)}"><span class="r-icon">${icon("book")}</span><span class="r-main"><div class="r-title">${hl(g.term, terms)}</div><div class="r-sub">${esc(g.text.replace(/[`*_]/g, "").slice(0, 110))}</div></span></a>`;
      });
    }
    palRes.innerHTML = html || `<div class="palette-empty">No results for “${esc(q)}”. Try a simpler word.</div>`;
    palSel = 0;
    markSel();
    $$(".res", palRes).forEach((a) => (a.onclick = closePalette));
  }
  function markSel() {
    $$(".res", palRes).forEach((r, i) => r.classList.toggle("sel", i === palSel));
    $$(".res", palRes)[palSel]?.scrollIntoView({ block: "nearest" });
  }
  palInput.addEventListener("input", () => drawResults(palInput.value));
  palInput.addEventListener("keydown", (e) => {
    if (e.key === "ArrowDown") { palSel = Math.min(palItems.length - 1, palSel + 1); markSel(); e.preventDefault(); }
    else if (e.key === "ArrowUp") { palSel = Math.max(0, palSel - 1); markSel(); e.preventDefault(); }
    else if (e.key === "Enter" && palItems[palSel]) { location.hash = palItems[palSel]; closePalette(); }
    else if (e.key === "Escape") closePalette();
  });
  pal.addEventListener("click", (e) => { if (e.target === pal) closePalette(); });
  $("#search-btn").onclick = openPalette;

  document.addEventListener("keydown", (e) => {
    const typing = /INPUT|TEXTAREA/.test(document.activeElement?.tagName) || document.activeElement?.closest?.(".CodeMirror");
    if ((e.ctrlKey || e.metaKey) && e.key.toLowerCase() === "k") { e.preventDefault(); pal.classList.contains("open") ? closePalette() : openPalette(); }
    else if (e.key === "/" && !typing) { e.preventDefault(); openPalette(); }
    else if (e.key === "Escape" && pal.classList.contains("open")) closePalette();
    else if (e.altKey && !typing && (e.key === "ArrowRight" || e.key === "ArrowLeft")) {
      const a = $(e.key === "ArrowRight" ? ".pager .next" : ".pager .prev");
      if (a) location.hash = a.getAttribute("href");
    }
  });

