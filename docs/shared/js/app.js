  function highlight(code, lang) {
    const mode = MODES[lang];
    if (!mode || !window.CodeMirror || !CodeMirror.runMode) return esc(code);
    let html = "";
    CodeMirror.runMode(code, mode, (text, style) => {
      html += style ? `<span class="${style.split(" ").map((s) => "tk-" + s).join(" ")}">${esc(text)}</span>` : esc(text);
    });
    return html;
  }

