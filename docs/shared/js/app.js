  function renderBlocks(blocks, container, cards) {
    blocks.forEach((b) => {
      if (b.t === "md") {
        container.insertAdjacentHTML("beforeend", md(b.text));
      } else if (b.t === "code") {
        if (b.lang === "quiz") container.appendChild(quizCard(b.code));
        else if (b.lang === "viz" && VIZ) VIZ.mount(container, b.meta.algo, b.code, b.meta);
        else if (b.lang === "math") container.insertAdjacentHTML("beforeend", tex(b.code, true));
        else {
          const c = codeCard(b);
          container.appendChild(c);
          cards.push(c);
        }
      } else if (b.t === "box") {
        if (b.kind === "solution" || b.kind === "hint") {
          const isHint = b.kind === "hint";
          const d = el(`<details class="box box-${b.kind}"><summary>${icon(isHint ? "bulb" : "eye")} ${mdInline(b.title || (isHint ? "Hint" : "Show solution"))}</summary><div class="box-body"></div></details>`);
          renderBlocks(b.children, $(".box-body", d), cards);
          container.appendChild(d);
        } else if (b.kind === "problem") {
          container.appendChild(problemCard(b, cards));
        } else if (b.kind === "tabs") {
          container.appendChild(tabsCard(b, cards));
        } else if (b.kind === "complexity") {
          container.appendChild(complexityCard(b.raw));
        } else if (b.kind === "derive") {
          container.appendChild(deriveCard(b.title, b.raw));
        } else if (b.kind === "flow") {
          const steps = b.raw.split("\n").map((s) => s.trim()).filter(Boolean);
          const f = el(`<div class="flow" role="list">${b.title ? `<div class="flow-title">${esc(b.title)}</div>` : ""}</div>`);
          steps.forEach((s, i) => {
            const [head, ...rest] = s.split("|");
            if (i) f.appendChild(el(`<span class="flow-arrow">${icon("right")}</span>`));
            f.appendChild(el(`<div class="flow-step" role="listitem"><span class="n">${i + 1}</span><b>${mdInline(head.trim())}</b>${rest.length ? `<small>${mdInline(rest.join("|").trim())}</small>` : ""}</div>`));
          });
          container.appendChild(f);
        } else if (b.kind === "formula") {
          container.appendChild(el(`<div class="formula">${tex(b.raw.trim(), true)}${b.title ? `<span class="cap">${mdInline(b.title)}</span>` : ""}</div>`));
        } else {
          const info = BOX[b.kind] || BOX.note;
          const label = b.kind === "def" ? info.label : (b.title && b.kind !== "def" ? info.label : info.label);
          const showTitle = b.title ? `<span class="sep">·</span><span class="box-title">${mdInline(b.title)}</span>` : "";
          const box = el(`<div class="box box-${esc(b.kind)}"><div class="box-head">${icon(info.icon)} ${label} ${showTitle}</div><div class="box-body"></div></div>`);
          if (b.kind === "def" && b.title) box.id = "def-" + slugify(b.title);
          renderBlocks(b.children, $(".box-body", box), cards);
          container.appendChild(box);
        }
      }
    });
  }

