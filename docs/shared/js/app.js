  let spyObserver;
  function setupScrollSpy(heads) {
    if (spyObserver) spyObserver.disconnect();
    if (!heads.length) return;
    const links = Object.fromEntries($$("#toc a[data-id]").map((a) => [a.dataset.id, a]));
    const visible = new Set();
    spyObserver = new IntersectionObserver((entries) => {
      entries.forEach((e) => (e.isIntersecting ? visible.add(e.target.id) : visible.delete(e.target.id)));
      let current = null;
      for (const h of heads) {
        if (h.getBoundingClientRect().top < window.innerHeight * 0.35) current = h.id;
      }
      Object.values(links).forEach((a) => a.classList.toggle("active", a.dataset.id === current));
    }, { rootMargin: "-60px 0px -60% 0px", threshold: [0, 1] });
    heads.forEach((h) => spyObserver.observe(h));
  }

