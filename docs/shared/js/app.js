  /* ------------------------------------------------------------ block parser
     Markdown plus:
       ```lang run title="..." level=easy      (code fence with meta)
       ```quiz                                 (? question / - wrong / + right / > why)
       :::kind Optional title ... :::          (def, syntax, tip, warn, note, ai, analogy,
                                                keypoints, exercise, solution, flow, formula)
  */
  function parseMeta(s) {
    const meta = {};
    const re = /([\w-]+)(?:=(?:"([^"]*)"|(\S+)))?/g;
    let m;
    while ((m = re.exec(s || ""))) meta[m[1]] = m[2] ?? m[3] ?? true;
    return meta;
  }

  function parseBlocks(src) {
    const lines = String(src || "").replace(/\r\n/g, "\n").split("\n");
    const out = [];
    let buf = [];
    const flush = () => { const t = buf.join("\n"); if (t.trim()) out.push({ t: "md", text: t }); buf = []; };
    for (let i = 0; i < lines.length; i++) {
      const line = lines[i];
      let m = line.match(/^(`{3,})([\w+-]*)\s*(.*)$/);
      if (m) {
        const fence = m[1];
        const code = [];
        i++;
        while (i < lines.length && !(lines[i].startsWith(fence) && /^`{3,}\s*$/.test(lines[i]))) { code.push(lines[i]); i++; }
        flush();
        out.push({ t: "code", lang: (m[2] || "text").toLowerCase(), meta: parseMeta(m[3]), code: code.join("\n") });
        continue;
      }
      m = line.match(/^:::(\w+)\s*(.*)$/);
      if (m) {
        const inner = [];
        let inFence = false, depth = 0;          // boxes can nest (e.g. :::hint inside :::problem)
        i++;
        while (i < lines.length) {
          const l = lines[i];
          if (/^`{3,}/.test(l)) inFence = !inFence;
          if (!inFence && /^:::\w+/.test(l)) depth++;
          if (!inFence && /^:::\s*$/.test(l)) { if (depth === 0) break; depth--; }
          inner.push(l);
          i++;
        }
        flush();
        out.push({ t: "box", kind: m[1].toLowerCase(), title: m[2].trim(), raw: inner.join("\n"), children: parseBlocks(inner.join("\n")) });
        continue;
      }
      buf.push(line);
    }
    flush();
    // a ```stdin block directly after a code block is that program's input
    for (let i = out.length - 1; i > 0; i--) {
      if (out[i].t === "code" && out[i].lang === "stdin" && out[i - 1].t === "code") { out[i - 1].stdin = out[i].code; out.splice(i, 1); }
    }
    return out;
  }

