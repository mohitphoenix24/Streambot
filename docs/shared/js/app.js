  function hydrateCard(card) {
    const { lang, meta, code } = card._block;
    const body = $(".code-body", card);
    let getCode = () => code;

    if (card._runnable && window.CodeMirror) {
      const cm = CodeMirror(body, {
        value: code,
        mode: MODES[lang] || lang,
        theme: "pg",
        lineNumbers: true,
        indentUnit: lang === "python" || lang === "cpp" ? 4 : 2,
        tabSize: lang === "python" || lang === "cpp" ? 4 : 2,
        indentWithTabs: false,
        viewportMargin: Infinity,
        matchBrackets: true,
        autoCloseBrackets: true,
        lineWrapping: false,
        extraKeys: {
          "Ctrl-Enter": () => run(),
          "Cmd-Enter": () => run(),
          "Shift-Enter": () => run(),
          "Ctrl-/": "toggleComment",
          "Cmd-/": "toggleComment",
          Tab: (c) => (c.somethingSelected() ? c.indentSelection("add") : c.replaceSelection(" ".repeat(c.getOption("indentUnit")), "end")),
          "Shift-Tab": (c) => c.indentSelection("subtract"),
        },
      });
      editors.push(cm);
      cm.on("change", () => {
        card.classList.toggle("edited", cm.getValue() !== code);
        if (Runner.onEdit) Runner.onEdit(ctx());
      });
      getCode = () => cm.getValue();
      card._cm = cm;
      body.appendChild(el(`<div class="code-hint"><span>✎ Editable: change anything and run it again</span><span><kbd>Ctrl</kbd> + <kbd>Enter</kbd> to run</span></div>`));
      // stdin box: shown when the example reads input, toggled with the Input button otherwise
      const stdinOrig = card._block.stdin || "";
      const stdinBox = el(`<div class="stdin-box" ${stdinOrig ? "" : "hidden"}><div class="stdin-head">${icon("terminal")} Input (stdin) <span>— what the program reads with <code>cin</code></span></div><textarea spellcheck="false" rows="${Math.min(8, Math.max(2, stdinOrig.split("\n").length))}"></textarea></div>`);
      const ta = $("textarea", stdinBox);
      ta.value = stdinOrig;
      $(".card-extra", card).appendChild(stdinBox);
      const stdinBtn = $(".act-stdin", card);
      stdinBtn.classList.toggle("on", !!stdinOrig);
      stdinBtn.onclick = () => { stdinBox.hidden = !stdinBox.hidden; stdinBtn.classList.toggle("on", !stdinBox.hidden); if (!stdinBox.hidden) ta.focus(); };
      ta.addEventListener("input", () => card.classList.toggle("edited", cm.getValue() !== code || ta.value !== stdinOrig));
      ta.addEventListener("keydown", (e) => { if ((e.ctrlKey || e.metaKey) && e.key === "Enter") { e.preventDefault(); run(); } });
      card._stdin = () => ta.value;
      $(".act-reset", card).onclick = () => { cm.setValue(code); ta.value = stdinOrig; card.classList.remove("edited"); };
    } else {
      body.innerHTML = `<pre class="static"><code>${highlight(code, lang)}</code></pre>`;
    }

    $(".act-copy", card).onclick = () => copyText(getCode());

    const runBtn = $(".act-run", card);
    let running = false;
    const lessonId = currentLessonId;
    const ctx = () => ({ code: getCode(), lang, meta, card, lessonId, stdin: card._stdin ? card._stdin() : undefined, output: (label) => outputPanel(card, label) });
    async function run() {
      if (!runBtn || running) return;
      running = true;
      runBtn.disabled = true;
      runBtn.classList.add("running");
      runBtn.innerHTML = `${icon("loader")}<span>Running</span>`;
      try { await Runner.run(ctx()); }
      catch (e) { const o = outputPanel(card); o.write(String(e && e.message || e) + "\n", "stderr"); o.status("Failed", "err"); }
      finally {
        running = false;
        runBtn.disabled = false;
        runBtn.classList.remove("running");
        runBtn.innerHTML = `${icon("play")}<span>Run</span>`;
      }
    }
    if (runBtn) runBtn.onclick = run;
    card._run = run;
  }

  /* ------------------------------------------------------------ quiz */
  function quizCard(src) {
    const qs = [];
    let cur = null;
    src.split("\n").forEach((line) => {
      const t = line.trim();
      if (!t) return;
      if (t.startsWith("? ")) { cur = { q: t.slice(2), opts: [], why: "" }; qs.push(cur); }
      else if (cur && (t.startsWith("- ") || t.startsWith("+ "))) cur.opts.push({ text: t.slice(2), ok: t[0] === "+" });
      else if (cur && t.startsWith("> ")) cur.why += (cur.why ? " " : "") + t.slice(2);
      else if (cur) cur.q += " " + t;
    });
    const card = el(`<div class="quiz"><div class="quiz-head">${icon("help")} Quick check <span class="score">0 / ${qs.length}</span></div></div>`);
    let answered = 0, correct = 0;
    qs.forEach((q, qi) => {
      const qEl = el(`<div class="quiz-q"><div class="q">${qs.length > 1 ? `${qi + 1}. ` : ""}${mdInline(q.q)}</div><div class="quiz-opts"></div><div class="quiz-explain"></div></div>`);
      const opts = $(".quiz-opts", qEl);
      q.opts.forEach((o) => {
        const b = el(`<button class="quiz-opt"><span class="mark"></span><span>${mdInline(o.text)}</span></button>`);
        b.onclick = () => {
          $$(".quiz-opt", opts).forEach((x, i) => {
            x.disabled = true;
            if (q.opts[i].ok) { x.classList.add("correct"); $(".mark", x).textContent = "✓"; }
          });
          if (!o.ok) { b.classList.add("wrong"); $(".mark", b).textContent = "✕"; }
          answered++; if (o.ok) correct++;
          $(".score", card).textContent = `${correct} / ${qs.length}`;
          const ex = $(".quiz-explain", qEl);
          ex.innerHTML = `<p><b>${o.ok ? "✅ Correct!" : "Not quite."}</b> ${mdInline(q.why)}</p>`;
          ex.classList.add("show");
        };
        opts.appendChild(b);
      });
      card.appendChild(qEl);
    });
    return card;
  }

